def run_sensitivity(ps: pd.DataFrame, base: StudyDesign, alpha: float) -> pd.DataFrame:
    """Re-run the headline comparison under reasonable alternative choices."""
    variants = {
        "Main specification": {},
        "Age <= 22": {"max_age": 22},
        "Age <= 26": {"max_age": 26},
        "Base-season MP >= 1,000": {"min_mp": 1000},
        "Base-season MP >= 300": {"min_mp": 300},
        "Next-season MP >= 500": {"min_mp_next": 500},
        "Exclude COVID outcome seasons": {"exclude_outcome_seasons": (2020, 2021)},
        "Inverse-probability weighting": {"use_ipw": True},
    }
    rows = []
    for name, kw in variants.items():
        design = base.with_(**kw)
        mt = features.build_model_table(ps, design)

        def factory(d=design):
            return [models.Marcel(),
                    models.SklearnModel("Ridge", features.ALL_FEATURES, "ridge", alpha,
                                        d.use_ipw)]

        preds = models.rolling_origin(mt, factory, design)
        boot = models.paired_bootstrap(preds, "Ridge", "Marcel", n_boot=1000)
        met = models.metrics_by_model(preds).set_index("model")
        sig = analysis.signal_regression(mt, use_ipw=design.use_ipw).set_index("feature")
        row = {"variant": name, "n_test": int(met.loc["Ridge", "n"]),
               "rmse_marcel": met.loc["Marcel", "rmse_w"], "rmse_ridge": met.loc["Ridge", "rmse_w"],
               "rmse_diff": boot["rmse_diff"], "ci_low": boot["ci_low"],
               "ci_high": boot["ci_high"]}
        row.update({f"coef_{f}": sig.loc[f, "coef_per_sd"] for f in KEY_SIGNALS})
        rows.append(row)
        log(f"  sensitivity: {name} diff={boot['rmse_diff']:+.3f}")
    return pd.DataFrame(rows)


def make_forecast(mt: pd.DataFrame, preds: pd.DataFrame, tuned: dict,
                  level: float = 0.8) -> pd.DataFrame:
    """Project next season for the latest base season, with conformal intervals."""
    latest = int(mt["season"].max())
    train = mt.loc[(mt["season"] < latest) & (mt["observed"] == 1)]
    target = mt.loc[mt["season"] == latest]
    ridge = models.SklearnModel("Ridge", features.ALL_FEATURES, "ridge",
                                tuned["ridge_alpha"]).fit(train)
    marcel = models.Marcel().fit(train)
    hw = models.interval_half_width(preds, "Ridge", level)
    fc = target[["player", "player_id", "season", "age", "team", "pos_group", "mp", "bpm",
                 "usg_percent", "ts_rel", "f_tr_rel", "ft_pct_shrunk", "gs_share"]].copy()
    fc["pred"] = ridge.predict(target)
    fc["marcel_pred"] = marcel.predict(target)
    fc["pred_delta"] = fc["pred"] - fc["bpm"]
    fc["model_minus_marcel"] = fc["pred"] - fc["marcel_pred"]
    fc["pred_low"], fc["pred_high"] = fc["pred"] - hw, fc["pred"] + hw
    fc["interval_level"] = level
    return fc.sort_values("pred_delta", ascending=False).reset_index(drop=True)


def run(sample: bool = False, offline: bool = False, refresh_sample: bool = False) -> dict:
    warnings.filterwarnings("ignore", category=RuntimeWarning)
    t0 = time.time()
    viz.setup_style()
    design = SAMPLE_DESIGN if sample else config.DEFAULT_DESIGN
    out_root = config.ROOT / "outputs" / "sample" if sample else config.REPORTS_DIR
    tables_dir, figs_dir = out_root / "tables", out_root / "figures"
    for d in (tables_dir, figs_dir):
        d.mkdir(parents=True, exist_ok=True)

    log(f"Loading data ({'sample' if sample else 'full'})")
    ps, meta = load_player_seasons(sample, offline)
    if not sample:
        config.PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
        ps.to_parquet(config.PROCESSED_DIR / "player_seasons.parquet", index=False)
        if refresh_sample or not SAMPLE_FILE.exists():
            write_sample(ps)
            log(f"Wrote sample extract to {SAMPLE_FILE.relative_to(config.ROOT)}")

    mt = features.build_model_table(ps, design)
    if not sample:
        mt.to_parquet(config.PROCESSED_DIR / "model_table.parquet", index=False)
    hist = mt.loc[mt["season"] < mt["season"].max()]
    log(f"Model table: {len(mt):,} rows; {int(hist['observed'].sum()):,} with observed outcome")

    # --- Exploratory analysis -------------------------------------------------
    rtm = analysis.regression_to_mean(mt)
    age = analysis.age_curve(hist)
    attr = analysis.attrition_by_projection(mt)
    naive = analysis.naive_most_improved(mt, int(mt["outcome_season"].max()) - 1)
    for name, df in [("regression_to_mean", rtm), ("age_curve", age),
                     ("attrition_by_projection", attr), ("naive_most_improved", naive)]:
        df.to_csv(tables_dir / f"{name}.csv", index=False)
    viz.regression_to_mean(rtm, figs_dir / "fig1_regression_to_mean.png")
    viz.age_and_attrition(age, attr, figs_dir / "fig2_age_and_attrition.png")

    # --- Interpretive model ---------------------------------------------------
    kept = [f for f in analysis.INTERPRETIVE_FEATURES if f not in analysis.COLLINEAR_DROP]
    corr_pair = analysis.max_abs_correlation(mt, kept)
    sig = analysis.signal_regression(mt)
    sig.to_csv(tables_dir / "signal_regression.csv", index=False)
    viz.signals(sig, figs_dir / "fig6_signals.png")

    # --- Predictive models ----------------------------------------------------
    log("Tuning hyperparameters on the pre-test era")
    tuned = models.tune(mt, design)
    log(f"  ridge alpha={tuned['ridge_alpha']}, gbm={tuned['gbm_params']}")
    log("Rolling-origin evaluation")
    preds = models.rolling_origin(
        mt, lambda: models.standard_models(features.ALL_FEATURES, tuned), design)
    preds.to_csv(tables_dir / "test_predictions.csv", index=False)
    metrics = models.metrics_by_model(preds)
    by_season = models.metrics_by_season(preds)
    boots = pd.DataFrame([models.paired_bootstrap(preds, m, "Marcel")
                          for m in ["Persistence", "Age curve", "Ridge", "Gradient boosting"]])
    metrics.to_csv(tables_dir / "model_metrics.csv", index=False)
    by_season.to_csv(tables_dir / "model_metrics_by_season.csv", index=False)
    boots.to_csv(tables_dir / "bootstrap_vs_marcel.csv", index=False)
    viz.model_comparison(metrics, boots, figs_dir / "fig3_model_comparison.png")
    viz.skill_by_season(by_season, figs_dir / "fig4_skill_by_season.png")
    viz.calibration(preds, figs_dir / "fig7_calibration.png")

    conf = models.online_conformal(preds, "Ridge", 0.8)
    conf["mp_bin"] = pd.cut(conf["mp_next"], [0, 1000, 2000, 5000],
                            labels=["250-999", "1,000-1,999", "2,000+"])
    coverage = conf.groupby("mp_bin", observed=True)["covered"].agg(["mean", "size"]).reset_index()
    coverage.to_csv(tables_dir / "interval_coverage_by_minutes.csv", index=False)

    ridge_p = preds.loc[preds["model"] == "Ridge"].assign(resid=lambda d: d["bpm_next"] - d["pred"])
    misses = pd.concat([ridge_p.nlargest(8, "resid").assign(kind="Outperformed forecast"),
                        ridge_p.nsmallest(8, "resid").assign(kind="Underperformed forecast")])
    misses.to_csv(tables_dir / "largest_misses.csv", index=False)

    log("Feature-group ablation")
    abl_preds = models.ablation(mt, design, tuned["ridge_alpha"])
    abl = pd.DataFrame([models.paired_bootstrap(abl_preds, m, "Core only")
                        for m in abl_preds["model"].unique() if m != "Core only"])
    abl = pd.concat([pd.DataFrame([{"model": "Core only", "reference": "Core only",
                                    "rmse_diff": 0.0, "ci_low": 0.0, "ci_high": 0.0}]), abl])
    abl = abl.merge(models.metrics_by_model(abl_preds)[["model", "rmse_w", "spearman_delta"]],
                    on="model")
    abl.to_csv(tables_dir / "ablation.csv", index=False)
    viz.ablation(abl, figs_dir / "fig5_ablation.png")

    log("Sensitivity analysis")
    sens = run_sensitivity(ps, design, tuned["ridge_alpha"])
    sens.to_csv(tables_dir / "sensitivity.csv", index=False)

    log("Forecasting next season")
    fc = make_forecast(mt, preds, tuned)
    fc.to_csv(tables_dir / "forecast_next_season.csv", index=False)
    viz.forecast(fc, figs_dir / "fig8_forecast.png")

    m = metrics.set_index("model")
    b = boots.set_index("model")
    results = {
        "mode": meta["mode"],
        "source_repo": config.SOURCE_REPO,
        "source_commit": config.SOURCE_COMMIT,
        "design": {k: (list(v) if isinstance(v, tuple) else v)
                   for k, v in design.__dict__.items()},
        "n_model_rows": int(len(mt)),
        "n_historical_rows": int(len(hist)),
        "n_observed": int(hist["observed"].sum()),
        "dropout_rate": float(1 - hist["observed"].mean()),
        "n_test_rows": int(m.loc["Ridge", "n"]),
        "test_seasons": [int(design.first_test_season) + 1, int(preds["season"].max()) + 1],
        "tuned": {"ridge_alpha": tuned["ridge_alpha"], "gbm_params": tuned["gbm_params"]},
        "metrics": metrics.set_index("model").round(4).to_dict(orient="index"),
        "ridge_vs_marcel": b.loc["Ridge"].to_dict(),
        "gbm_vs_marcel": b.loc["Gradient boosting"].to_dict(),
        "base_rate_improve": float((preds.loc[preds["model"] == "Ridge", "delta_bpm"]
                                    >= config.IMPROVEMENT_THRESHOLD).mean()),
        "ridge_skill_pct": float((1 - m.loc["Ridge", "rmse_w"] / m.loc["Marcel", "rmse_w"]) * 100),
        "interval_80_coverage": float(conf["covered"].mean()),
        "interval_80_half_width": float(models.interval_half_width(preds, "Ridge")),
        "signal_regression_r2": sig.attrs["r2"],
        "max_abs_corr_interpretive": {"pair": corr_pair[:2], "r": corr_pair[2]},
        "marcel_k_full": float(models.Marcel().fit(hist.loc[hist["observed"] == 1]).k),
        "forecast_base_season": int(mt["season"].max()),
        "runtime_sec": round(time.time() - t0, 1),
    }
    (tables_dir / "results.json").write_text(json.dumps(results, indent=2, default=float))
    (tables_dir / "data_provenance.json").write_text(json.dumps(meta, indent=2, default=str))
    log(f"Done in {results['runtime_sec']}s. Outputs in {out_root.relative_to(config.ROOT)}/")
    return results


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--sample", action="store_true",
                   help="use the bundled sample extract (no network needed)")
    p.add_argument("--offline", action="store_true",
                   help="use cached raw files only; never download")
    p.add_argument("--refresh-sample", action="store_true",
                   help="regenerate data/sample/ from the full data")
    args = p.parse_args()
    try:
        run(sample=args.sample, offline=args.offline, refresh_sample=args.refresh_sample)
    except (acquire.DataUnavailableError, schema.SchemaError) as e:
        raise SystemExit(f"ERROR: {e}")


if __name__ == "__main__":
    main()
