"""End-to-end analysis: raw data -> tables, figures, and a results summary.

Usage::

    python -m bbs.pipeline            # full analysis (downloads ~25 MB once)
    python -m bbs.pipeline --sample   # offline run on the bundled sample
"""

from __future__ import annotations

import argparse
import json
import time
import warnings
from pathlib import Path

import pandas as pd

from bbs import analysis, config, features, models, viz
from bbs.config import StudyDesign
from bbs.data import acquire, clean, schema

SAMPLE_FILE = config.SAMPLE_DIR / "player_seasons_sample.csv.gz"
SAMPLE_FIRST_SEASON = 2012
# The sample keeps fewer seasons, so the test window starts later.
SAMPLE_DESIGN = config.DEFAULT_DESIGN.with_(
    first_base_season=2014, tuning_cutoff=2018, first_test_season=2019)

# Columns the model table and the dashboard need.
SAMPLE_COLUMNS = [
    "season", "player", "player_id", "age", "team", "pos", "pos_group", "g", "gs", "mp",
    "per", "ts_percent", "usg_percent", "ast_percent", "tov_percent", "orb_percent",
    "drb_percent", "stl_percent", "blk_percent", "x3p_ar", "f_tr", "ws_48", "obpm",
    "dbpm", "bpm", "vorp", "x3p", "x3pa", "ft", "fta", "x3pa_per_100_poss",
    "avg_dist_fga", "percent_fga_from_x0_3_range", "fg_percent_from_x0_3_range",
    "percent_assisted_x2p_fg", "percent_dunks_of_fga",
    "on_court_plus_minus_per_100_poss", "net_plus_minus_per_100_poss", "experience",
    "team_srs", "n_teams", "traded", "height_in", "weight_lb", "draft_pick", "undrafted",
    "ts_rel", "x3p_ar_rel", "f_tr_rel", "ft_pct_shrunk", "x3p_pct_shrunk",
]

KEY_SIGNALS = ["ts_rel", "f_tr_rel", "ft_pct_shrunk", "usg_percent", "tov_percent", "gs_share"]


def log(msg: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


# --------------------------------------------------------------------------
# Data
# --------------------------------------------------------------------------

def load_player_seasons(sample: bool, offline: bool) -> tuple[pd.DataFrame, dict]:
    """Return the cleaned player-season table and provenance metadata."""
    if sample:
        if not SAMPLE_FILE.exists():
            raise acquire.DataUnavailableError(
                f"Sample file not found: {SAMPLE_FILE}. It is generated by the first full "
                "run (`python -m bbs.pipeline`) and is not distributed with the repository.")
        ps = pd.read_csv(SAMPLE_FILE)
        return ps, {"mode": "sample", "file": str(SAMPLE_FILE.relative_to(config.ROOT)),
                    "rows": len(ps)}

    tables = acquire.load_raw(download=not offline)
    schema.validate_all(tables)
    cl = clean.CleaningLog()
    ps = clean.build_player_seasons(tables, log=cl)
    ps = features.add_era_adjusted(ps, tables["team_summaries"])
    ps, priors = features.add_shrunk_shooting(ps, config.DEFAULT_DESIGN.tuning_cutoff)
    completeness = {int(s): round(clean.season_completeness(tables["team_summaries"], s), 3)
                    for s in range(config.FIRST_SEASON, config.LAST_SEASON + 1)}
    manifest_path = config.RAW_DIR / "manifest.json"
    meta = {
        "mode": "full",
        "source_repo": config.SOURCE_REPO,
        "source_commit": config.SOURCE_COMMIT,
        "files": json.loads(manifest_path.read_text()) if manifest_path.exists() else {},
        "cleaning_log": cl.steps,
        "shrinkage_priors": priors,
        "season_completeness": completeness,
        "rows": len(ps),
    }
    return ps, meta


def write_sample(ps: pd.DataFrame, path: Path = SAMPLE_FILE) -> Path:
    """Write the local extract used for offline re-runs and tests (git-ignored)."""
    s = ps.loc[ps["season"] >= SAMPLE_FIRST_SEASON, SAMPLE_COLUMNS].copy()
    s = s.round(4)
    path.parent.mkdir(parents=True, exist_ok=True)
    s.to_csv(path, index=False, compression="gzip")
    return path


